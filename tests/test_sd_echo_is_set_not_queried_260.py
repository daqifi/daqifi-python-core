class _SplitEveryEcho(_Device):
    """Every setter echo is cut by the budget: CR just inside, LF just
    outside. The audit's schedule, repeated."""

    cr_at = 1.9
    lf_at = 2.1

    def _enqueue(self, data, delay):
        blob = bytes(data)
        member = _family_member(blob)
        if member is not None and blob.endswith(b"\r\n"):
            super()._enqueue(blob[:-1], self.cr_at)
            super()._enqueue(b"\n", self.lf_at)
            return
        super()._enqueue(blob, delay)


class _CutAtLastDigit(_Device):
    """Delivers a setter echo's TEXT but WITHHOLDS its terminator, which can
    then be released one byte at a time.

    ⛔ THE r15 AUDIT'S OWN :2102 SCHEDULE, taken from the artifact rather
    than from the summary of it: "deliver its echo through the final digit
    before the deadline, leaving pending suffix b'\r\n'. Deliver b'\r' and
    retry: reclamation consumes it but retains the unchanged suffix.
    Deliver b'\n' and retry: it no longer matches b'\r\n', so the pending
    partial is discarded without releasing the spelling."

    ⚠ My first attempt at this cell used `_SplitEveryEcho` (CR inside the
    budget, LF outside) and MEASURED GREEN at 2a71e9d2 for recovery -- r15's
    bookkeeping survives that schedule, releasing 3 of 4 spellings. It is a
    neighbouring case, not the finding, and a cell built on it would have
    been another inert differential.
    """

    def _enqueue(self, data, delay):
        blob = bytes(data)
        member = _family_member(blob)
        if member is not None and blob.endswith(b"\r\n"):
            super()._enqueue(member, delay)          # the text, no terminator
            self.held = [b"\r", b"\n"]               # released by hand
            return
        super()._enqueue(blob, delay)

    def deliver_held(self):
        """Release one withheld terminator byte, in order, FIFO-correct."""
        held = getattr(self, "held", None)
        if held:
            super()._enqueue(held.pop(0), 0.0)


